#!/usr/bin/env python3
"""OpenAY Mic logo icon generator (committed, one-time use).

Renders of the committed glyph SVG (`assets/openay-mic-glyph.svg`, produced
by resvg) are turned into the three icon artifacts:

- `src/logo_icon.rs`  — the 128x128 logo as a raw RGBA byte array, included
  by the GUI for the window icon (iced `window::Icon::from_rgba`), following
  the same embed-raw-pixels pattern as `src/icons.rs`.
- `assets/icons/openay-mic.ico` — a multi-size Windows icon (16..256, BMP
  entries) embedded into the Windows executable via build.rs / winresource.
- `android/app/src/main/res/mipmap-*/ic_launcher_foreground.png` — the
  adaptive launcher icon foreground layers (108 dp grid per density).

Run after re-rendering:
    for s in 16 24 32 48 64 128 256; do resvg --width $s --height $s \\
        assets/openay-mic-glyph.svg /tmp/iconwork/glyph-$s.png; done
    for s in 108 162 216 324 432; do resvg --width $s --height $s \\
        assets/openay-mic-glyph.svg /tmp/iconwork/fg-$s.png; done
    python3 tools/gen_logo_icons.py /tmp/iconwork
"""

import os
import struct
import sys
import zlib

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.dirname(os.path.abspath(__file__))))))
ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]
FG_DPI = {108: "mdpi", 162: "hdpi", 216: "xhdpi", 324: "xxhdpi", 432: "xxxhdpi"}


def decode_png(path):
    """Minimal PNG decoder: 8-bit RGBA8, non-interlaced, filters 0-4."""
    raw = open(path, "rb").read()
    assert raw[:8] == b"\x89PNG\r\n\x1a\n", f"{path}: not a PNG"
    pos, idat, meta = 8, b"", None
    while pos < len(raw):
        (length,) = struct.unpack(">I", raw[pos:pos + 4])
        ctype = raw[pos + 4:pos + 8]
        data = raw[pos + 8:pos + 8 + length]
        if ctype == b"IHDR":
            w, h, depth, color, _, _, interlace = struct.unpack(
                ">IIBBBBB", data)
            meta = (w, h, depth, color, interlace)
        elif ctype == b"IDAT":
            idat += data
        elif ctype == b"IEND":
            break
        pos += 12 + length
    w, h, depth, color, interlace = meta
    assert (depth, color, interlace) == (8, 6, 0), \
        f"{path}: expected 8-bit RGBA non-interlaced, got {meta}"
    # Unfilter scanlines.
    out = bytearray()
    prev = bytearray(w * 4)
    stride, src = w * 4, 0
    scan = zlib.decompress(idat)
    for _ in range(h):
        ftype = scan[src]
        line = bytearray(scan[src + 1:src + 1 + stride])
        src += 1 + stride
        for i in range(stride):
            a = line[i - 4] if i >= 4 else 0
            b = prev[i]
            c = prev[i - 4] if i >= 4 else 0
            if ftype == 1:
                line[i] = (line[i] + a) & 0xFF
            elif ftype == 2:
                line[i] = (line[i] + b) & 0xFF
            elif ftype == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif ftype == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pr = a if (pa <= pb and pa <= pc) else \
                    (b if pb <= pc else c)
                line[i] = (line[i] + pr) & 0xFF
        out += line
        prev = line
    return w, h, bytes(out)


def write_logo_rs(path, w, h, rgba):
    def fmt(data, indent):
        lines = []
        for i in range(0, len(data), 20):
            chunk = data[i:i + 20]
            lines.append(indent + " ".join(f"{b}," for b in chunk))
        return "\n".join(lines)
    body = fmt(rgba, "    ")
    with open(path, "w") as f:
        f.write(
            "// OpenAY Mic — window icon (logo glyph), raw RGBA.\n"
            "// Generated by tools/gen_logo_icons.py from "
            "assets/openay-mic-glyph.svg — do not edit by hand.\n\n"
            f"/// Logo glyph rasterized to {w}x{h} RGBA for the window icon.\n"
            f"pub const LOGO_W: u32 = {w};\n"
            f"pub const LOGO_H: u32 = {h};\n"
            f"pub static LOGO_RGBA: [u8; {w * h * 4}] = [\n{body}\n];\n")
    print(f"wrote {path} ({w}x{h} RGBA)")


def write_ico(path, images):
    """Multi-size ICO with 32-bit BMP entries (BITMAPINFOHEADER + BGRA rows
    bottom-up + empty AND mask)."""
    entries, blobs = [], b""
    for w, h, rgba in images:
        stride = w * 4
        bgra = bytearray()
        for y in range(h - 1, -1, -1):  # bottom-up
            row = rgba[y * stride:(y + 1) * stride]
            for x in range(w):
                r, g, b, a = row[x * 4:x * 4 + 4]
                bgra += bytes((b, g, r, a))
        bmp = struct.pack(
            "<IiiHHIIiiII", 40, w, h * 2, 1, 32, 0, stride * h,
            0, 0, 0, 0)  # BITMAPINFOHEADER: h*2 covers the (empty) AND mask
        mask_row = ((w + 31) // 32) * 4
        bmp += bgra + bytes(mask_row * h)  # fully-opaque AND mask (alpha wins)
        entries.append((w, len(bmp), len(blobs)))
        blobs += bmp
        if w < 256:
            pass
    count = len(entries)
    ico = struct.pack("<HHH", 0, 1, count)
    for w, size, off in entries:
        ico += struct.pack("<BBBBHHII", (w % 256), (w % 256), 0, 0, 1, 32,
                           size, 6 + 16 * count + off)
    ico += blobs
    open(path, "wb").write(ico)
    print(f"wrote {path} ({len(ico)} bytes, {count} sizes)")


def main():
    work = sys.argv[1] if len(sys.argv) > 1 else "/tmp/iconwork"
    # 1. Window icon module (128x128 RGBA).
    w, h, rgba = decode_png(f"{work}/glyph-128.png")
    assert (w, h) == (128, 128)
    write_logo_rs(os.path.join(REPO, "desktop/crates/openay-gui/src/"
                               "logo_icon.rs"), w, h, rgba)
    # 2. Windows .ico (BMP entries from the decoded renders).
    images = [decode_png(f"{work}/glyph-{s}.png") for s in ICO_SIZES]
    write_ico(os.path.join(REPO, "assets/icons/openay-mic.ico"), images)
    # 3. Android adaptive-icon foregrounds (108 dp grid, per density).
    for px, dpi in FG_DPI.items():
        wp, hp, data = decode_png(f"{work}/fg-{px}.png")
        assert (wp, hp) == (px, px)
        dst = os.path.join(REPO, f"android/app/src/main/res/"
                                 f"mipmap-{dpi}/ic_launcher_foreground.png")
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        open(dst, "wb").write(open(f"{work}/fg-{px}.png", "rb").read())
        print(f"wrote {dst}")


if __name__ == "__main__":
    main()
